const fs = require("node:fs");
const path = require("node:path");

const root = process.cwd();

function p(...parts) {
  return path.join(root, ...parts);
}

function ensureDir(dir) {
  fs.mkdirSync(dir, { recursive: true });
}

function write(file, content) {
  ensureDir(path.dirname(file));
  fs.writeFileSync(file, content.replace(/\r?\n/g, "\r\n"), "utf8");
  console.log("Wrote " + path.relative(root, file));
}

function exists(file) {
  return fs.existsSync(file);
}

function read(file) {
  if (!exists(file)) return "";
  return fs.readFileSync(file, "utf8");
}

function patch(file, updater) {
  const before = read(file);
  const after = updater(before);

  if (after === before) {
    console.log("OK no change needed: " + path.relative(root, file));
    return;
  }

  ensureDir(path.dirname(file));
  fs.writeFileSync(file, after, "utf8");
  console.log("Patched " + path.relative(root, file));
}

function updatePackageScript(packagePath, name, command) {
  if (!exists(packagePath)) return;

  const json = JSON.parse(read(packagePath));
  json.scripts = json.scripts || {};
  json.scripts[name] = command;

  fs.writeFileSync(packagePath, JSON.stringify(json, null, 2) + "\n", "utf8");
  console.log("Updated package script " + name + " in " + path.relative(root, packagePath));
}

