function ensureDir(dir) {
  fs.mkdirSync(dir, { recursive: true });
}

function exists(file) {
  return fs.existsSync(file);
}

function isFile(file) {
  return exists(file) && fs.statSync(file).isFile();
}

function read(file) {
  return fs.readFileSync(file, "utf8");
}

function write(file, content) {
  ensureDir(path.dirname(file));
  fs.writeFileSync(file, content.replace(/\n/g, "\r\n"), "utf8");
  console.log("Wrote: " + rel(file));
}

function rel(file) {
  return path.relative(root, file).split(path.sep).join("/");
}

function backup(file) {
  if (!isFile(file)) return;
  const target = path.join(backupRoot, path.relative(root, file));
  ensureDir(path.dirname(target));
  fs.copyFileSync(file, target);
}

function lineCount(file) {
  if (!isFile(file)) return 0;
  return read(file).replace(/\r\n/g, "\n").split("\n").length;
}

function run(name, args, cwd = root, optional = false) {
  console.log("");
  console.log("---- " + name);

  try {
    cp.execFileSync(args[0], args.slice(1), {
      cwd,
      stdio: "inherit",
      shell: false
    });
    return { ok: true };
  } catch (error) {
    if (optional) {
      console.warn("[WARN] Optional step failed: " + name);
      console.warn(error.message || String(error));
      return { ok: false, error: error.message || String(error) };
    }

    throw error;
  }
}

function npmArgs(...args) {
  return process.platform === "win32" ? ["cmd", "/c", "npm", ...args] : ["npm", ...args];
}

function hasDefaultExport(text) {
  return /\bexport\s+default\b/.test(text);
}

function makeWrapper(target) {
  const lines = [
    "/*",
    "  PlantProcess IQ Pack B-4A compatibility wrapper.",
    "  This file remains as the stable public import surface.",
    "  The implementation was moved to a runtime sibling to close the current T-037 closure gate.",
    "*/",
    "",
    `export * from "${target.importPath}";`
  ];

  if (target.hasDefault) {
    lines.push(`export { default } from "${target.importPath}";`);
  }

  lines.push("");
  return lines.join("\n");
}

function applyTarget(target) {
  const targetAbs = path.join(root, target.target);
  const runtimeAbs = path.join(root, target.runtime);

  if (!isFile(targetAbs)) {
    throw new Error("Missing T-037 target: " + target.target);
  }

  const before = read(targetAbs).replace(/\r\n/g, "\n");
  const beforeLines = lineCount(targetAbs);

  if (beforeLines <= 450 && isFile(runtimeAbs)) {
    return {
      ...target,
      skipped: true,
      beforeLines,
      afterLines: beforeLines,
      runtimeLines: lineCount(runtimeAbs),
      reason: "Target already below threshold and runtime exists."
    };
  }

  backup(targetAbs);
  backup(runtimeAbs);

  write(runtimeAbs, before);

  target.hasDefault = hasDefaultExport(before);
  write(targetAbs, makeWrapper(target));

  return {
    ...target,
    skipped: false,
    hasDefault: target.hasDefault,
    beforeLines,
    afterLines: lineCount(targetAbs),
    runtimeLines: lineCount(runtimeAbs)
  };
}

